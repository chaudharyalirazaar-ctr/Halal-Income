Object.keys(extraStrings).forEach((lang) => {
  if (!translations[lang]) translations[lang] = {};
  Object.assign(translations[lang], extraStrings[lang]);
});

function applyLanguage(lang) {
  const dict = translations[lang] || translations.en;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });

  const rtlLangs = ["ar", "ur", "fa"];
  document.documentElement.setAttribute("dir", rtlLangs.includes(lang) ? "rtl" : "ltr");

  const currentLabel = document.getElementById("lang-current");
  if (currentLabel) currentLabel.textContent = lang.toUpperCase();

  localStorage.setItem("siteLang", lang);
}

document.addEventListener("DOMContentLoaded", () => {
  const savedLang = localStorage.getItem("siteLang") || "en";
  applyLanguage(savedLang);

  const toggle = document.getElementById("lang-toggle");
  const menu = document.getElementById("lang-menu");

  if (toggle && menu) {
    toggle.addEventListener("click", () => {
      const isOpen = menu.classList.toggle("lang-menu-open");
      toggle.setAttribute("aria-expanded", isOpen ? "true" : "false");
    });

    menu.querySelectorAll("button[data-lang]").forEach((btn) => {
      btn.addEventListener("click", () => {
        applyLanguage(btn.dataset.lang);
        menu.classList.remove("lang-menu-open");
      });
    });

    document.addEventListener("click", (e) => {
      if (!toggle.contains(e.target) && !menu.contains(e.target)) {
        menu.classList.remove("lang-menu-open");
      }
    });
  }
});
